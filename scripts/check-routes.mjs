// Route & link verification against a running server.
//   node scripts/check-routes.mjs [baseUrl]   (default http://localhost:3460)
// Checks every captured page route, every blog post URL and every tag /
// category archive; verifies archives list exactly the posts their metadata
// says; then follows every internal link found in the rendered HTML.
// Writes docs/implementation/route-checklist.md.
import fs from 'node:fs';
import path from 'node:path';

const BASE = process.argv[2] || 'http://localhost:3460';
const ROOT = process.cwd();
const pages = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/generated/pages.json'), 'utf8'));
const posts = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/generated/posts.json'), 'utf8'));

const enc = (n) => encodeURIComponent(n).replace(/%20/g, '+');
const tally = (key) => {
  const m = new Map();
  posts.forEach((p) => p[key].forEach((t) => m.set(t, [...(m.get(t) || []), p.url])));
  return m;
};
const tags = tally('tags');
const cats = tally('categories');

const routes = [
  ...Object.keys(pages).map((r) => ({ kind: 'page', url: r })),
  ...posts.map((p) => ({ kind: 'post', url: p.url, title: p.title })),
  ...[...cats].map(([n, urls]) => ({ kind: 'category', url: `/blog/category/${enc(n)}`, name: n, expect: urls })),
  ...[...tags].map(([n, urls]) => ({ kind: 'tag', url: `/blog/tag/${enc(n)}`, name: n, expect: urls })),
];

const results = [];
const internal = new Set();
const unescape = (s) => s.replace(/&amp;/g, '&').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');

async function get(url) {
  const res = await fetch(BASE + url, { redirect: 'manual' });
  const text = res.status === 200 ? await res.text() : '';
  return { status: res.status, text, location: res.headers.get('location') };
}

const CONC = 6;
let idx = 0;
async function worker() {
  while (idx < routes.length) {
    const r = routes[idx++];
    const { status, text } = await get(r.url);
    const h1 = (text.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1]?.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim() || '';
    const h1Text = unescape(h1);
    const issues = [];
    if (status !== 200) issues.push(`HTTP ${status}`);
    if (status === 200 && !h1) issues.push('no <h1>');
    if (/squarespace\.com\/(?!static)|jason-buchanan-l386/i.test(text.replace(/static1\.squarespace\.com[^"]*/g, ''))) issues.push('squarespace link');
    if (r.kind === 'post' && h1Text !== r.title.replace(/\s+/g, ' ').trim()) issues.push(`h1 mismatch: "${h1}"`);
    if (r.expect) {
      // Archive grid: post links inside the archive section (before the "All articles" footer)
      const section = text.split('aria-label="Articles:')[1]?.split('</section>')[0] || '';
      const found = [...new Set([...section.matchAll(/href="([^"]+)"/g)].map((m) => unescape(m[1])))];
      const missing = r.expect.filter((u) => !found.includes(u));
      const extra = found.filter((u) => !r.expect.includes(u));
      if (missing.length || extra.length) issues.push(`archive mismatch (missing ${missing.length}, extra ${extra.length})`);
      r.count = found.length;
    }
    for (const m of text.matchAll(/href="(\/[^"#]*)/g)) {
      const u = unescape(m[1]);
      if (!u.startsWith('/_next') && !/\.(webp|png|jpg|ico|mp3|xml|txt)$/.test(u)) internal.add(u.split('?')[0]);
    }
    results.push({ ...r, status, h1, issues });
  }
}
await Promise.all(Array.from({ length: CONC }, worker));

// Follow every internal link discovered in the rendered pages.
const known = new Set(routes.map((r) => r.url));
const linkResults = [];
for (const u of [...internal].filter((u) => !known.has(u))) {
  const { status, location } = await get(u);
  linkResults.push({ url: u, status, location });
}
const badLinks = linkResults.filter((l) => l.status !== 200 && !(l.status >= 300 && l.status < 400));

const by = (k) => results.filter((r) => r.kind === k);
const ok = (list) => list.filter((r) => !r.issues.length).length;
const lines = [];
lines.push('# Route checklist', '', `Generated by \`scripts/check-routes.mjs\` against ${BASE} on ${new Date().toISOString().slice(0, 10)}.`, '');
lines.push('| Group | Routes | Passing |', '|---|---|---|');
for (const k of ['page', 'post', 'category', 'tag']) lines.push(`| ${k} | ${by(k).length} | ${ok(by(k))} |`);
lines.push('', `Internal links discovered in rendered HTML: ${internal.size} unique. Extra (non-route) links followed: ${linkResults.length}; broken: ${badLinks.length}.`, '');
if (badLinks.length) lines.push('## Broken internal links', ...badLinks.map((l) => `- ${l.url} → ${l.status}`), '');
for (const k of ['page', 'post', 'category', 'tag']) {
  lines.push(`## ${k[0].toUpperCase() + k.slice(1)} routes (${by(k).length})`, '', '| ✓ | URL | H1 | Notes |', '|---|---|---|---|');
  by(k)
    .sort((a, b) => a.url.localeCompare(b.url))
    .forEach((r) => lines.push(`| ${r.issues.length ? '✗' : '✓'} | \`${r.url}\` | ${r.h1.replace(/\|/g, '\\|').slice(0, 70)} | ${r.count != null ? `${r.count} posts listed (expected ${r.expect.length}) ` : ''}${r.issues.join('; ')} |`));
  lines.push('');
}
fs.mkdirSync(path.join(ROOT, 'docs/implementation'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/implementation/route-checklist.md'), lines.join('\n'));
for (const k of ['page', 'post', 'category', 'tag']) console.log(`${k}: ${ok(by(k))}/${by(k).length} passing`);
console.log(`internal links: ${internal.size} unique, broken: ${badLinks.length}`);
results.filter((r) => r.issues.length).forEach((r) => console.log('FAIL', r.url, r.issues.join('; ')));
badLinks.forEach((l) => console.log('BROKEN LINK', l.url, l.status));
